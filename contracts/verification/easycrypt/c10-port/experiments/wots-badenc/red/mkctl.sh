#!/bin/sh
# Regenerate the MUST-FAIL negative controls for BadEncSplit.ec (STEP 1).
#
# Each control DELETES INFORMATION at exactly one site and leaves the proof
# script's intro arity unchanged, so the file fails because a hypothesis is
# missing -- not because the syntax broke.
#
#   CtlA  `badenc_splits_gated`: the +C gate `P (ThC ps ad x c)` -> `true`.
#         The (B2) branch can then no longer produce `P dg` (nor `P dg'` via
#         `P_transfers_across_codeword`).
#   CtlB  `badenc_splits_gated`: the (B1) DISJUNCT -> `false`.  THIS IS THE
#         CONTROL THAT GUARDS THE HEADLINE.  If it compiles green then "B1 is
#         empty" is baked into the split itself and the whole finding is
#         worthless -- report that loudly.
#   CtlC  `split_under_freshness`: the freshness hypothesis -> `true`.  Tests
#         that freshness, and nothing else, is what collapses the split to (B2).
#   CtlD  `B2_is_tcoll_win_core`: the digest INEQUALITY -> `true`.  Tests that
#         landing in T_COLL_RES_ENUM's residual really needs `dg <> dg'`.
#
# ALL FOUR MUST FAIL.  Run with ./runctl.sh; receipts in controls/Ctl?.out.
set -eu
cd "$(dirname "$0")"
mkdir -p controls
banner() {
cat <<'EOF'
(* #########################################################################
   MUST-FAIL NEGATIVE CONTROL -- NOT A RESULT.  DO NOT PROMOTE OR VENDOR.
   Generated by ../mkctl.sh from ../BadEncSplit.ec with exactly one site
   mutated so that INFORMATION is deleted (intro arity unchanged).
   THIS FILE IS EXPECTED TO FAIL TO COMPILE.  Receipts: controls/Ctl?.out.
   ######################################################################### *)
EOF
}

# CtlA -- the +C gate premise of badenc_splits_gated (anchored by the B1 line
#         that follows it, so the substitution cannot hit the other three
#         lemmas that carry a textually identical premise).
{ banner; perl -0777 -pe 's/  => P \(ThC ps ad x c\)\n  =>    \(ThC ps ad x c = ThC/  => true\n  =>    (ThC ps ad x c = ThC/s' BadEncSplit.ec; } > controls/CtlA.ec

# CtlB -- the (B1) disjunct itself.
{ banner; perl -0777 -pe 's/  =>    \(ThC ps ad x c = ThC ps ad x. c.\)                          \(\* B1 \*\)/  =>    false                                                     (* B1 *)/s' BadEncSplit.ec; } > controls/CtlB.ec

# CtlC -- the freshness premise of split_under_freshness (anchored by its
#         in-line marker comment, which occurs exactly once).
{ banner; perl -0777 -pe 's/     ThC ps ad x c <> ThC ps ad x. c.                            \(\* = is_fresh \*\)/     true                                                        (* = is_fresh *)/s' BadEncSplit.ec; } > controls/CtlC.ec

# CtlD -- the digest inequality premise of B2_is_tcoll_win_core (anchored by
#         the two `P` premises that follow it).
{ banner; perl -0777 -pe 's/     ThC ps ad x c <> ThC ps ad x. c.\n  => P \(ThC ps ad x c\)\n  => P \(ThC ps ad x. c.\)/     true\n  => P (ThC ps ad x c)\n  => P (ThC ps ad x\x27 c\x27)/s' BadEncSplit.ec; } > controls/CtlD.ec

# ---- STEP 2/3 controls, from BadEncToTColl.ec --------------------------------
#   CtlE  `badenc_target_from_inv`: the `wads_parallel` premise -> `true`.
#         THE load-bearing invariant: without it the two ThC images sit at
#         unrelated tweaks and the conclusion is not EncNonInjOnThCSurface.
#   CtlF  `badenc_target_from_inv`: the `qs_ThC_images` premise -> `true`.
#         Without it the retrieved message is not known to be a ThC image at
#         all, so there is no (ps, ad) to instantiate the residual with.
#   CtlG  `badenc_target`: the `m' <> m` (is_fresh) conjunct -> `true`.
#         This is the control that guards the "B1 is empty at this boundary"
#         claim AT THE GAME LEVEL: delete freshness and the (B2) witness cannot
#         be produced.
#   CtlZ  anti-fail-open: append `lemma NEGCTL : false` proved by `trivial`.
#         If THIS compiles the file is not being checked at all.

# CtlE
{ banner; perl -0777 -pe 's/     wads_parallel wads qs\n  => qs_ThC_images ps qs\n  => badenc_target/     true\n  => qs_ThC_images ps qs\n  => badenc_target/s' BadEncToTColl.ec; } > controls/CtlE.ec
# CtlF
{ banner; perl -0777 -pe 's/  => qs_ThC_images ps qs\n  => badenc_target ps qs i/  => true\n  => badenc_target ps qs i/s' BadEncToTColl.ec; } > controls/CtlF.ec
# CtlG
{ banner; perl -0777 -pe 's/      \/\\ m. <> m                                          \(\* is_fresh \*\)/      \/\\ true                                              (* is_fresh *)/s' BadEncToTColl.ec; } > controls/CtlG.ec
# CtlZ
{ banner; cat BadEncToTColl.ec; printf '\nlemma NEGCTL : false.\nproof. trivial. qed.\n'; } > controls/CtlZ.ec

chmod 666 controls/*.ec 2>/dev/null || true

# Fail loudly if a control is byte-identical to the source: that would make the
# control vacuous (it would compile green for the trivial reason).
for f in CtlA CtlB CtlC CtlD; do
  if diff -q <(tail -n +8 "controls/$f.ec") BadEncSplit.ec > /dev/null 2>&1; then
    echo "FATAL: controls/$f.ec is unmutated -- the anchor did not match" >&2
    exit 1
  fi
done
for f in CtlE CtlF CtlG; do
  if diff -q <(tail -n +8 "controls/$f.ec") BadEncToTColl.ec > /dev/null 2>&1; then
    echo "FATAL: controls/$f.ec is unmutated -- the anchor did not match" >&2
    exit 1
  fi
done
echo "controls regenerated; every mutation anchor matched"
