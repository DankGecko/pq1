def main() -> int:
    if installed_tool_version() != OFFICIAL_TOOL_VERSION:
        raise RuntimeError(
            f"erc7730 package must be exactly {OFFICIAL_TOOL_VERSION}; "
            "run via `make erc7730-cross-parity`"
        )
    expected_root, expected_count = parse_production_descriptor_receipt(
        ROOTS_SOURCE.read_text(encoding="utf-8")
    )
    expected_curation_sha256 = hashlib.sha256(CURATION_MANIFEST.read_bytes()).hexdigest()
    entries = validate_generated_review(
        REVIEW.read_bytes(),
        expected_root=expected_root,
        expected_count=expected_count,
        expected_curation_sha256=expected_curation_sha256,
    )
    formats = 0
    fields = 0
    for descriptor in DESCRIPTORS:
        descriptor_formats, descriptor_fields = compare_descriptor(descriptor, entries)
        formats += descriptor_formats
        fields += descriptor_fields
    run_pq1_renderer_conformance()
    print(
        "ERC-7730 cross parity: PASS "
        f"({len(DESCRIPTORS)} production descriptors, {formats} formats, {fields} fields; "
        "exact generator round-trip + official resolver + Merkle-verified "
        "PQ1 renderer conformance)"
    )
    return 0


